// words.final.json -> audio excerpts + Hypit Sources, one production per edit.
//   node tools/gen_source.mjs [--no-audio] [--accent warm]
// Word timing lives in each Timeline as named Instants (editable in Studio); the design lives in
// packages/pixel-lyrics/client/scenes/<edit>.js. The edit name is the scene-set name.
// --accent warm writes a second production set (productions/<edit>-warm/) with the orange accent.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { isAbsolute, resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const W = JSON.parse(readFileSync(resolve(root, "productions/words.final.json"), "utf8"));
const LEAD = W.lead ?? 0.35;           // frames: a word is on screen this much before its onset (rounded to the frame grid)
const FPS = W.fps ?? 30;
const arg = (k, d) => { const i = process.argv.indexOf("--" + k); return i < 0 ? d : process.argv[i + 1]; };
const accent = arg("accent", W.accent ?? "cold");
if (accent !== "cold" && accent !== "warm") throw new Error("accent must be cold or warm");
const suffix = accent === (W.accent ?? "cold") ? "" : "-" + accent;
const esc = s => s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");
const cutAudio = !process.argv.includes("--no-audio");

for (const [name, E] of Object.entries(W.edits)) {
  if (!/^[a-z][a-z0-9_]*$/.test(name)) throw new Error(`Edit name "${name}" must be lowercase letters, digits, underscores (it names the scene-set file).`);
  const words = W.words.filter(w => w.edit === name).map((w, i) => ({ id: "w" + String(i).padStart(2, "0"), text: w.text,
    f: Math.max(0, Math.round((w.start - E.start) * FPS - LEAD)) }));
  if (!words.length) throw new Error(`Edit "${name}" has no words.`);
  for (let i = 1; i < words.length; i++) if (words[i].f <= words[i - 1].f) words[i].f = words[i - 1].f + 1;
  if (words.at(-1).f >= E.frames) throw new Error(`Edit "${name}": last word lands on frame ${words.at(-1).f}, but the edit has ${E.frames} frames.`);

  // audio excerpt: a little longer than the picture; the Audio Clip window trims and fades it
  const wav = resolve(root, `assets/audio/${name}.wav`);
  if (cutAudio && W.audio) {
    const src = isAbsolute(W.audio) ? W.audio : resolve(root, W.audio);
    if (!existsSync(src)) throw new Error(`Audio not found: ${src}`);
    mkdirSync(resolve(root, "assets/audio"), { recursive: true });
    execFileSync("ffmpeg", ["-v", "error", "-y", "-ss", String(E.start), "-t", (E.frames / FPS + 0.1).toFixed(3), "-i", src, "-c:a", "pcm_s16le", wav]);
  }
  if (!existsSync(wav)) throw new Error(`Missing ${wav}. Set "audio" in words.final.json or cut it yourself.`);

  const svml = `<?svml using="@hypit/markup@1"?>
<!-- GENERATED by tools/gen_source.mjs from productions/words.final.json. Track ${E.start}s + ${E.frames}f @ ${FPS} fps. -->
<svml>
  <import as="time" from="@hypit/timeline-author@1"/>
  <import as="space" from="@hypit/spatial@1"/>
  <import as="media" from="@hypit/media@1"/>
  <import as="mediaop" from="@hypit/media-operations@1"/>
  <import as="audio" from="@hypit/audio-track@1"/>
  <import as="px" from="@kit/pixel-lyrics@1"/>
  <import as="film" from="@hypit/film@1"/>
  <import as="html" from="@hypit/html-video@1"/>
  <import as="look" source="../look.svs"/>

  <time:Clock id="clock" frame-rate="${FPS}"/>
  <time:Timeline id="t" clock={clock} end="${E.frames}f">
${words.map(w => `    <time:Instant id="${w.id}" at="${w.f}f"/>`).join("\n")}
  </time:Timeline>
  <space:Canvas id="canvas" width="1080" height="1920"/>

  <media:Audio id="song" src="../../assets/audio/${name}.wav"/>
  <mediaop:Normalize id="song-media" source={song} clock={clock} video="none" audio="default" span-authority="audio"/>
  <audio:Track id="mix" timeline={t.timeline}>
    <audio:Clip id="song-clip" source={song-media.media} during={t.window} fade-in="1f" fade-out="3f"/>
  </audio:Track>

  <px:Edit id="edit" timeline={t.timeline} within={canvas.bounds} during={t.window} variant="${name}" accent="${accent}">
${words.map(w => `    <px:Word id="${w.id}" text="${esc(w.text)}" at={t.${w.id}}/>`).join("\n")}
  </px:Edit>

  <film:Film id="main" canvas={canvas.canvas} timeline={t.timeline} appearance={look.film.main}>
    <film:Track source={edit.visual}/>
    <film:Track source={mix.audio}/>
  </film:Film>
  <html:Video id="final" composition={main.composition} timeline={t.timeline}/>
</svml>
`;
  mkdirSync(resolve(root, `productions/${name}${suffix}`), { recursive: true });
  writeFileSync(resolve(root, `productions/${name}${suffix}/main.svml`), svml);
  writeFileSync(resolve(root, `productions/${name}${suffix}/main.svrun`), `<?svml using="@hypit/markup/run@1"?>\n\n<svrun version="1">\n  <author source="./main.svml"/>\n  <target output="final.video"/>\n</svrun>\n`);
  console.log(`${name}${suffix}: ${words.length} words, ${E.frames} frames, accent ${accent}\n  ` + words.map((w, i) => `${i}:${w.text}@${w.f}`).join(" "));
}
writeFileSync(resolve(root, "productions/look.svs"), `<?svml using="@hypit/recipe@1"?>\n<sheet version="1">\n  film.main { background: #050507; }\n</sheet>\n`);
