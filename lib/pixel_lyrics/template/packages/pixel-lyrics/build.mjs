// Inline the browser-side code, the pictures and the pixel font (client/) into src/generated.ts so the Producer stays pure.
// engine.js first, then every scene set in client/scenes/ (alphabetical); client/img/*.jpg|png; client/font/*.woff2.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
const here = new URL("./client/", import.meta.url);
const read = name => readFileSync(new URL(name, here), "utf8");
const b64 = name => readFileSync(new URL(name, here)).toString("base64");
const scenes = readdirSync(new URL("scenes/", here)).filter(n => n.endsWith(".js")).sort().map(n => "scenes/" + n);
if (!scenes.length) throw new Error("No scene sets in client/scenes/. Write client/scenes/<edit>.js first.");
const setup = ["engine.js", ...scenes].map(read).join("\n") + "\nreturn setupPixel(root, data);\n";
const MIME = { jpg: "image/jpeg", png: "image/png" };
const images = Object.fromEntries(readdirSync(new URL("img/", here)).filter(f => /\.(jpg|png)$/.test(f)).sort()
  .map(f => [f.slice(0, -4), `data:${MIME[f.slice(-3)]};base64,` + b64("img/" + f)]));
if (!Object.keys(images).length) throw new Error("No pictures in client/img/. Run tools/prep_img.py first.");
const fonts = [
  { url: "data:font/woff2;base64," + b64("font/cyrillic.woff2"), range: "U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116" },
  { url: "data:font/woff2;base64," + b64("font/latin.woff2"), range: "U+0000-00FF,U+2000-206F,U+20AC,U+2212" },
];
writeFileSync(new URL("./src/generated.ts", import.meta.url),
  "// GENERATED by build.mjs from client/ — edit the client files, not this one.\n" +
  `export const SETUP = ${JSON.stringify(setup)};\n` +
  `export const IMAGES: Record<string, string> = ${JSON.stringify(images)};\n` +
  `export const FONTS: { url: string; range: string }[] = ${JSON.stringify(fonts)};\n`);
console.log(`generated.ts: ${scenes.length} scene set(s), setup ${setup.length} B, ${Object.keys(images).length} images, ${fonts.length} fonts`);
