// Inline the browser-side code (client/) into src/generated.ts so the Producer stays pure.
// engine.* comes first, then every scene set in client/scenes/ (alphabetical).
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
const here = new URL("./client/", import.meta.url);
const read = name => readFileSync(new URL(name, here), "utf8");
const scenes = ext => readdirSync(new URL("scenes/", here)).filter(n => n.endsWith(ext)).sort().map(n => "scenes/" + n);
const css = ["engine.css", ...scenes(".css")].map(read).join("\n");
const setup = ["engine.js", ...scenes(".js")].map(read).join("\n") + "\nreturn setupEdit(root, data);\n";
if (!scenes(".js").length) throw new Error("No scene sets in client/scenes/. Write client/scenes/<edit>.js first.");
writeFileSync(new URL("./src/generated.ts", import.meta.url),
  `// GENERATED by build.mjs from client/ — edit the client files, not this one.\nexport const CSS = ${JSON.stringify(css)};\nexport const SETUP = ${JSON.stringify(setup)};\n`);
console.log(`generated.ts: ${scenes(".js").length} scene set(s), css ${css.length} B, setup ${setup.length} B`);
